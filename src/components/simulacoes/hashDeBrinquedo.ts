// Hash de BRINQUEDO só para as simulações (32 bits, misturando bem os bits). Não serve para proteger nada de verdade.
export function hashDeBrinquedo(texto: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < texto.length; i++) {
    h ^= texto.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  h ^= h >>> 16
  h = Math.imul(h, 0x85ebca6b)
  h ^= h >>> 13
  h = Math.imul(h, 0xc2b2ae35)
  h ^= h >>> 16
  return (h >>> 0).toString(16).padStart(8, '0')
}
